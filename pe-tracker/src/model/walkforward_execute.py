"""Execution path for the frozen ``first_walkforward_v1`` protocol.

Built at Isaiah's direction (2026-10-21) as a *replication* runner: the
out-of-sample windows of this protocol were already published in PR #23, so a
run of this module is a replication of public results, NOT a fresh
out-of-sample test.

Fail-closed gates (all must pass before any fit):
  1. protocol.json ``execution_authorized`` is true (``refuse_execution``);
  2. the caller supplies the exact ``authorization_command_required`` phrase;
  3. protocol.json carries an ``authorization_record`` with approver + time;
  4. protocol status is not already ``EXECUTED`` (execute once);
  5. protocol forbids calibration / tuning / random k-fold, and the locked
     model contract matches the live constants (``assert_locked_contract``);
  6. the plan regenerated by the frozen prep code from the live store is
     identical to the committed ``plan.json`` (cohort identity, per-window
     counts, row identities and dataset fingerprints).

Per window the protocol sequence is delegated, unchanged, to
``validation.fit_and_score``: fit break_logit_v1 on PIT training rows ->
select t* on training in-sample predictions only -> freeze t* -> grade the
untouched test window (feature time in (cutoff, next_cutoff_or_horizon],
labels known by horizon), with constant and spread-only baselines.

There are deliberately no tuning knobs: hyperparameters, cutoffs, horizon,
threshold rule and metrics are read from the locked protocol / locked code.
Registration uses ``register_model`` into the ephemeral in-memory store only;
nothing is written to the on-disk canonical SQLite store.

The SEC contact (``SEC_USER_AGENT``) is read from the environment by the SEC
provider at runtime. Its value is never written to any output; the writer
refuses to emit a file containing it.
"""
