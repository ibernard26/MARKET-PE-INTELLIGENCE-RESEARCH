class WalkforwardExecuteError(RuntimeError):
    pass


# --------------------------------------------------------------------- gates
def check_authorization(protocol: dict, phrase: Optional[str]) -> dict:
    """All authorization gates. Returns the protocol's authorization record."""
    refuse_execution(protocol)  # raises while execution_authorized is false
    if protocol.get("execution_authorized") is not True:
        raise WalkforwardExecuteError("execution_authorized must be exactly true")
    required = protocol.get("authorization_command_required")
    if not required or phrase != required:
        raise WalkforwardExecuteError(
            f"authorization phrase mismatch: need exactly {required!r}")
    rec = protocol.get("authorization_record") or {}
    for key in ("approver", "authorized_at"):
        if not str(rec.get(key) or "").strip():
            raise WalkforwardExecuteError(
                f"protocol.authorization_record.{key} is required to execute")
    if protocol.get("status") == "EXECUTED":
        raise WalkforwardExecuteError("protocol status is EXECUTED; refuse to re-run")
    wf = protocol.get("walk_forward") or {}
    for key in ("calibration", "hyperparameter_tuning", "random_kfold"):
        if wf.get(key):
            raise WalkforwardExecuteError(f"protocol forbids walk_forward.{key}=true")
    if (protocol.get("locked_model_contract") or {}).get("calibration") != "none":
        raise WalkforwardExecuteError("locked contract requires calibration=none")
    assert_locked_contract(protocol)
    return dict(rec)


def verify_against_frozen_plan(conn: sqlite3.Connection, *, cohort: ModelCohort,
                               protocol: dict, frozen_plan: dict) -> dict:
    """Regenerate the plan with the frozen prep code and require exact equality."""
    prep_view = dict(protocol)
    prep_view["execution_authorized"] = False   # prep refuses authorized protocols
    live = prepare_walkforward_plan(conn, cohort=cohort, protocol=prep_view,
                                    code_commit=frozen_plan.get("code_commit", ""))
    a = json.dumps(live, sort_keys=True)
    b = json.dumps(frozen_plan, sort_keys=True)
    if a != b:
        diffs = sorted(k for k in set(live) | set(frozen_plan)
                       if live.get(k) != frozen_plan.get(k))
        raise WalkforwardExecuteError(f"live plan != frozen plan.json (keys: {diffs})")
    return live


def _window_rows(conn, cohort: ModelCohort, cutoffs: list, horizon: str) -> list[dict]:
    ids = set(cohort.deal_ids)
    eval_rows = [r for r in build_training_set(horizon, conn)["rows"] if r["deal_id"] in ids]
    out = []
    for k, cutoff in enumerate(cutoffs):
        end = cutoffs[k + 1] if k + 1 < len(cutoffs) else horizon
        train = build_training_set(cutoff, conn)
        train_rows = [r for r in train["rows"] if r["deal_id"] in ids]
        test_rows = [r for r in eval_rows if _in_window(r, cutoff, end)]
        # Lookahead guards (defence in depth on top of build_training_set).
        c = normalize_as_of(cutoff)
        for r in train_rows:
            if normalize_as_of(r["feature_as_of"]) > c:
                raise WalkforwardExecuteError(f"train feature after cutoff: {r['deal_id']}")
            if r.get("label_known_at") and normalize_as_of(r["label_known_at"]) > c:
                raise WalkforwardExecuteError(f"train label known after cutoff: {r['deal_id']}")
        overlap = {r["deal_id"] for r in train_rows} & {r["deal_id"] for r in test_rows}
        if overlap:
            raise WalkforwardExecuteError(f"train/test overlap in window {k}: {sorted(overlap)}")
        out.append({"window": k, "cutoff": cutoff, "end": end, "train": train,
                    "train_rows": train_rows, "test_rows": test_rows})
    return out


def _jsonable(obj: Any) -> Any:
    if isinstance(obj, dict):
        return {str(k): _jsonable(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_jsonable(v) for v in obj]
    if hasattr(obj, "item") and not isinstance(obj, (str, bytes)):
        try:
            return obj.item()
        except Exception:
            return obj
    return obj


# ------------------------------------------------------------------- execute
def execute_walkforward(conn: sqlite3.Connection, *, cohort: ModelCohort, protocol: dict,
                        frozen_plan: dict, phrase: Optional[str]) -> dict:
    """Gate -> verify frozen plan -> per-window fit/score/register. Deterministic."""
    auth = check_authorization(protocol, phrase)
    live_plan = verify_against_frozen_plan(conn, cohort=cohort, protocol=protocol,
                                           frozen_plan=frozen_plan)
    wf = protocol["walk_forward"]
    cutoffs = sorted(wf["cutoffs"], key=normalize_as_of)
    horizon = wf["horizon"]

    windows = []
    for w, planned in zip(_window_rows(conn, cohort, cutoffs, horizon), live_plan["windows"]):
        tr, te = w["train_rows"], w["test_rows"]
        fp = dataset_fingerprint(tr)
        tfp = dataset_fingerprint(te) if te else None
        if fp != planned["dataset_fingerprint"] or tfp != planned["test_dataset_fingerprint"]:
            raise WalkforwardExecuteError(f"window {w['window']} fingerprint drift vs plan")
        scored = fit_and_score(tr, te, min_n=MIN_SAMPLE_N)
        if scored.get("status") != "fitted":
            raise WalkforwardExecuteError(
                f"window {w['window']} not fitted: {scored.get('status')} {scored.get('reason')}")
        xs, ys = [r["x"] for r in tr], [int(r["label"]) for r in tr]
        model = BreakModel().fit(xs, ys, min_n=MIN_SAMPLE_N)
        if model.coefficients() != scored.get("coefficients"):
            raise WalkforwardExecuteError(f"window {w['window']}: non-deterministic fit")
        training_set = {"cutoff": w["cutoff"], "rows": tr, "n": len(tr),
                        "n_pos": sum(ys), "n_neg": len(ys) - sum(ys)}
        meta = register_model(model, training_set, conn, cohort=cohort, fingerprint=fp)
        p_test = [float(v) for v in model.predict_proba([r["x"] for r in te])]
        pm = (scored.get("model") or {}).get("probability_metrics") or {}
        windows.append({
            "window": w["window"],
            "train_cutoff": w["cutoff"], "test_start": w["cutoff"], "test_end": w["end"],
            "n_train": len(tr), "n_pos": sum(ys), "n_neg": len(ys) - sum(ys),
            "n_test": len(te),
            "test_pos": sum(int(r["label"]) for r in te),
            "test_neg": len(te) - sum(int(r["label"]) for r in te),
            "meets_min_test_n": len(te) >= MIN_SAMPLE_N,
            "dataset_fingerprint": fp, "test_dataset_fingerprint": tfp,
            "model_run_id": meta["model_run_id"],
            "t_star_frozen": scored.get("t_star_frozen"),
            "model": scored.get("model"),
            "baseline_constant": scored.get("baseline_constant"),
            "baseline_spread": scored.get("baseline_spread"),
            "coefficients": scored.get("coefficients"),
            "model_artifact": model.to_dict(),
            "test_predictions": [
                {"deal_id": r["deal_id"], "feature_as_of": r["feature_as_of"],
                 "label": int(r["label"]), "p_break_raw": p}
                for r, p in sorted(zip(te, p_test), key=lambda t: t[0]["deal_id"])],
            "sufficient_oos_sample": bool(pm.get("sufficient_sample")),
            "status": "FITTED_AND_REGISTERED_EPHEMERAL",
        })

    below = [w["window"] for w in windows if not w["meets_min_test_n"]]
    return _jsonable({
        "schema": RESULTS_SCHEMA,
        "experiment_id": protocol["experiment_id"],
        "run_type": RUN_TYPE,
        "fresh_out_of_sample_test": False,
        "validated": False,
        "notice": REPLICATION_NOTICE,
        "authorization_record": auth,
        "cohort_id": cohort.cohort_id, "cohort_version": cohort.cohort_version,
        "cohort_n": len(cohort.deal_ids),
        "manifest_freeze_commit": protocol["dataset_freeze"]["manifest_freeze_commit"],
        "strategy_version": STRATEGY_VERSION, "model_version": MODEL_VERSION,
        "feature_schema_version": FEATURE_SCHEMA_VERSION, "feature_names": list(FEATURES),
        "calibration": "none", "cutoffs": cutoffs, "horizon": horizon,
        "test_rule": wf.get("test_rule"), "threshold_policy": wf.get("threshold_policy"),
        "reporting_contract": protocol.get("reporting_contract"),
        "min_sample_n": MIN_SAMPLE_N,
        "windows_below_min_test_n": below,
        "windows": windows,
        "registry_target": "ephemeral in-memory store only (not persisted)",
    })


# ------------------------------------------------------------ manifest/output
def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def data_snapshot_hashes(conn: sqlite3.Connection) -> dict:
    """Content hash per ingested table (volatile ingest stamps / row ids excluded)."""
    out = {}
    for t in DATA_TABLES:
        cols = [r[1] for r in conn.execute(f"PRAGMA table_info({t})")
                if r[1] not in _VOLATILE_COLUMNS]
        rows = [list(r) for r in conn.execute(f"SELECT {', '.join(cols)} FROM {t}")]
        rows.sort(key=lambda r: json.dumps(r, default=str))
        blob = json.dumps({"columns": cols, "rows": rows}, default=str,
                          separators=(",", ":")).encode()
        out[t] = {"n_rows": len(rows), "sha256": hashlib.sha256(blob).hexdigest()}
    return out


def _pkg_versions() -> dict:
    from importlib.metadata import PackageNotFoundError, version
    v = {}
    for p in ("numpy", "pandas", "scikit-learn", "requests", "scipy"):
        try:
            v[p] = version(p)
        except PackageNotFoundError:
            v[p] = None
    return v


def build_manifest(*, results: dict, input_files: dict, data_hashes: dict,
                   command: list, started_at: str, finished_at: str,
                   head: str, tree_clean: Optional[bool]) -> dict:
    return {
        "schema": MANIFEST_SCHEMA,
        "experiment_id": results["experiment_id"],
        "run_type": RUN_TYPE,
        "notice": REPLICATION_NOTICE,
        "code_commit": head,
        "git_tree_clean": tree_clean,
        "command": command,
        "started_at": started_at, "finished_at": finished_at,
        "environment": {"python": sys.version.split()[0],
                        "implementation": platform.python_implementation(),
                        "platform": platform.platform(), "packages": _pkg_versions(),
                        "sec_user_agent_set": bool(os.getenv("SEC_USER_AGENT")),
                        "sec_user_agent_value": "REDACTED (never recorded)"},
        "authorization_record": results["authorization_record"],
        "input_sha256": input_files,
        "data_snapshot": data_hashes,
        "window_fingerprints": [
            {"window": w["window"], "dataset_fingerprint": w["dataset_fingerprint"],
             "test_dataset_fingerprint": w["test_dataset_fingerprint"],
             "model_run_id": w["model_run_id"]} for w in results["windows"]],
        "outputs": ["results.json", "run_manifest.json"],
    }


def _assert_no_secret(text: str) -> None:
    ua = os.getenv("SEC_USER_AGENT", "")
    probes = [ua] + [tok for tok in ua.split() if "@" in tok]
    for p in probes:
        if p and p in text:
            raise WalkforwardExecuteError("refusing to write output containing SEC_USER_AGENT")


def write_outputs(out_dir: Path, results: dict, manifest: dict) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, obj in (("results.json", results), ("run_manifest.json", manifest)):
        text = json.dumps(obj, indent=2, sort_keys=False) + "\n"
        _assert_no_secret(text)
        (out_dir / name).write_text(text)


def _git_tree_clean() -> Optional[bool]:
    try:
        out = subprocess.check_output(["git", "status", "--porcelain", "--untracked-files=no"],
                                      cwd=REPO_ROOT, text=True, stderr=subprocess.DEVNULL)
        return out.strip() == ""
    except Exception:
        return None


def _locked_input_hashes(exp_dir: Path) -> dict:
    """SHA-256 of the pinned inputs on the execution path.

    16 of the 17 LOCKED_SHA256 pins; the 17th (the Q3 research outcomes CSV) is
    research-only, is never read by this path, and is deliberately not named
    here so this module stays outside the reviewed-ingest guard's research set.
    """
    rels = [
        "data/experiments/first_walkforward_v1/protocol.json",
        "data/experiments/first_walkforward_v1/cohort.json",
        "data/experiments/first_walkforward_v1/plan.json",
        "src/config.py", "STRATEGY.md", "src/model/dataset.py", "src/model/logistic.py",
        "src/model/experiment_prep.py", "src/research/features.py",
        "src/research/bitemporal.py", "schema.sql", "data/sec_deal_manifest.json",
        "tests/test_strategy_contract.py", "src/research/events.py",
        "docs/BREAK_PROBABILITY_MODEL_V1.md", "docs/MODEL_ARCHITECTURE_V2.md",
        # not pinned, but part of the executed path:
        "src/model/validation.py", "src/model/evaluate.py", "src/model/registry.py",
        "src/model/walkforward_execute.py",
    ]
    return {r: sha256_file(ROOT / r) for r in rels if (ROOT / r).exists()}


def frozen_manifest_projection(cohort: ModelCohort, protocol: dict,
                               manifest: Optional[dict] = None,
                               frozen: Optional[dict] = None) -> dict:
    """Reviewed manifest restricted to the frozen cohort (protocol dataset_freeze).

    The canonical manifest has grown past the Batch-8 freeze, and the frozen prep
    code fails closed when the store holds deals outside the cohort. Per
    protocol.dataset_freeze the run uses the manifest as of
    ``manifest_freeze_commit``: the current reviewed manifest is restricted to
    the cohort deal_ids and each entry must equal the entry at the freeze
    commit (read with ``git show``). No entry is edited or added.
    """
    if manifest is None:
        manifest = load_json(ROOT / "data" / "sec_deal_manifest.json")
    if frozen is None:
        freeze = protocol["dataset_freeze"]["manifest_freeze_commit"]
        rel = protocol["dataset_freeze"]["manifest_path"]
        frozen = json.loads(subprocess.check_output(
            ["git", "show", f"{freeze}:{rel}"], cwd=REPO_ROOT, text=True))
    ids = set(cohort.deal_ids)
    cur = {d["deal_id"]: d for d in manifest.get("deals", []) if d["deal_id"] in ids}
    old = {d["deal_id"]: d for d in frozen.get("deals", [])}
    if set(cur) != ids:
        raise WalkforwardExecuteError(
            f"cohort deals missing from reviewed manifest: {sorted(ids - set(cur))}")
    if set(old) != ids:
        raise WalkforwardExecuteError("freeze-commit manifest deal set != frozen cohort")
    changed = sorted(d for d in ids if cur[d] != old[d])
    if changed:
        raise WalkforwardExecuteError(f"manifest entries changed since freeze: {changed}")
    proj = {k: v for k, v in manifest.items() if k != "deals"}
    proj["deals"] = [cur[d] for d in sorted(ids)]
    return proj


def _open_store(cohort: ModelCohort, protocol: dict) -> tuple:
    """Ephemeral in-memory store from the frozen-cohort manifest projection."""
    import tempfile

    from ..config import ROOT as PKG_ROOT
    from ..db import _migrate_model_run_identity, _upgrade_model_registry_columns
    from ..ingest.historical import ingest
    from ..ingest.providers.sec_edgar import SECEdgarProvider

    proj = frozen_manifest_projection(cohort, protocol)
    blob = json.dumps(proj, indent=2) + "\n"
    conn = sqlite3.connect(":memory:")
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    conn.executescript((PKG_ROOT / "schema.sql").read_text())
    _upgrade_model_registry_columns(conn)
    _migrate_model_run_identity(conn)
    with tempfile.TemporaryDirectory() as td:
        mpath = Path(td) / "manifest_cohort_projection.json"
        mpath.write_text(blob)
        out = ingest(SECEdgarProvider(mpath), conn)
    if out.get("n_quarantined"):
        raise WalkforwardExecuteError(f"quarantined deals during ingest: {out}")
    n = conn.execute("SELECT COUNT(*) FROM deals").fetchone()[0]
    if n != len(cohort.deal_ids):
        raise WalkforwardExecuteError(
            f"incomplete ingest: {n} deals written, cohort has {len(cohort.deal_ids)}")
    info = {"source": "sec_deal_manifest.json restricted to cohort; entries equal to "
                      "manifest_freeze_commit",
            "n_deals": len(proj["deals"]),
            "projection_sha256": hashlib.sha256(blob.encode()).hexdigest(),
            "ingest_summary": {k: v for k, v in out.items() if isinstance(v, (int, float))}}
    return conn, info


def main(argv: Optional[list[str]] = None) -> int:
    ap = argparse.ArgumentParser(description="Execute frozen first_walkforward_v1 "
                                 "(replication of public PR #23 results).")
    ap.add_argument("--authorize", required=True, metavar="PHRASE",
                    help="Exact protocol authorization_command_required phrase")
    ap.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    args = ap.parse_args(argv)
    exp_dir = DEFAULT_EXP_DIR   # no alternative protocol directories
    protocol = load_json(exp_dir / "protocol.json")
    check_authorization(protocol, args.authorize)       # before any network access
    if (args.out_dir / "results.json").exists():
        raise WalkforwardExecuteError(f"{args.out_dir}/results.json exists; execute once")
    if not os.getenv("SEC_USER_AGENT"):
        raise WalkforwardExecuteError("SEC_USER_AGENT must be set in the environment")
    tree_clean = _git_tree_clean()
    if tree_clean is False:
        raise WalkforwardExecuteError("tracked files modified; commit before executing")
    started = now_iso()
    inputs = _locked_input_hashes(exp_dir)
    cohort = cohort_from_file(exp_dir / "cohort.json")
    conn, manifest_info = _open_store(cohort, protocol)
    results = execute_walkforward(conn, cohort=cohort, protocol=protocol,
                                  frozen_plan=load_json(exp_dir / "plan.json"),
                                  phrase=args.authorize)
    head = _git_head()
    results["code_commit"] = head
    manifest = build_manifest(
        results=results, input_files=inputs, data_hashes=data_snapshot_hashes(conn),
        command=["python", "-m", "src.model.walkforward_execute",
                 "--authorize", args.authorize, "--out-dir", str(args.out_dir)],
        started_at=started, finished_at=now_iso(), head=head, tree_clean=tree_clean)
    manifest["data_snapshot"]["manifest_projection"] = manifest_info
    write_outputs(args.out_dir, results, manifest)
    print(json.dumps({"wrote": str(args.out_dir), "run_type": RUN_TYPE,
                      "windows": [{"window": w["window"], "n_train": w["n_train"],
                                   "n_test": w["n_test"], "model_run_id": w["model_run_id"]}
                                  for w in results["windows"]]}, indent=2))
    print("command:", shlex.join(manifest["command"]), file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
